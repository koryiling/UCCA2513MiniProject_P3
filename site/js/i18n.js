const LANGS = [
  ["en", "EN"],
  ["zh", "中文"],
  ["ms", "BM"],
];

// A link such as index.html?lang=zh opens the site in that language.
const urlLang = new URLSearchParams(location.search).get("lang");
if (I18N[urlLang]) localStorage.setItem("uaa_lang", urlLang);

function getLang() {
  const lang = localStorage.getItem("uaa_lang");
  return I18N[lang] ? lang : "en";
}

// Translate a key; falls back to English, then to the given default text.
function t(key, fallback) {
  return I18N[getLang()][key] ?? I18N.en[key] ?? fallback ?? key;
}

// Language switcher buttons: <div class="lang-switch">EN | 中文 | BM</div>
function langSwitchHtml() {
  const lang = getLang();
  return `<div class="lang-switch" role="group" aria-label="Language">
    ${LANGS.map(([code, label]) =>
      `<button type="button" data-lang="${code}"${code === lang ? ' class="active" aria-pressed="true"' : ""}>${label}</button>`
    ).join("")}
  </div>`;
}

// Replace the English text in the page with the chosen language.
// English is already in the HTML, so switching language reloads the page.
function initI18n() {
  const lang = getLang();
  document.documentElement.lang = { en: "en", zh: "zh-Hans", ms: "ms" }[lang];

  if (lang !== "en") {
    const dict = I18N[lang];
    document.querySelectorAll("[data-i18n]").forEach(el => {
      const text = dict[el.dataset.i18n];
      if (text != null) el.innerHTML = text;
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
      const text = dict[el.dataset.i18nPlaceholder];
      if (text != null) el.placeholder = text;
    });
  }

  document.querySelectorAll("[data-lang]").forEach(btn =>
    btn.addEventListener("click", () => {
      if (btn.dataset.lang === lang) return;
      localStorage.setItem("uaa_lang", btn.dataset.lang);
      location.reload();
    })
  );
}
